#!/usr/bin/env python3
"""Generates src/KeccakF1600.sol: the Keccak-f[1600] permutation (FIPS 202 §3.3)
as Yul with one fully unrolled round inside a 24-iteration loop.

The EVM KECCAK256 opcode cannot produce SHAKE256 output (different padding,
and the permutation is not exposed between squeeze blocks), so the matrix
expansion needs the bare permutation. Regenerate with:
    python3 contracts/script/gen_keccak.py > contracts/src/KeccakF1600.sol
"""

# r[x][y] rotation offsets (FIPS 202 Table 2).
R = [
    [0, 36, 3, 41, 18],
    [1, 44, 10, 45, 2],
    [62, 6, 43, 15, 61],
    [28, 55, 25, 21, 56],
    [27, 20, 39, 8, 14],
]
RC = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
    0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
    0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
    0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
    0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]
M = "0xffffffffffffffff"


def off(i):
    return f"add(s, {32 * i})" if i else "s"


def toff(i):
    return f"add(t, {32 * i})" if i else "t"


def rol(expr, n):
    if n == 0:
        return expr
    return f"and(or(shl({n}, {expr}), shr({64 - n}, {expr})), {M})"


out = []
w = out.append
w("// SPDX-License-Identifier: MIT")
w("// GENERATED by contracts/script/gen_keccak.py. Do not edit by hand.")
w("pragma solidity 0.8.28;")
w("")
w("/// @notice Keccak-f[1600] (FIPS 202) over a 25-lane state in memory.")
w("/// Lane (x, y) is the 64-bit word at s + 32·(x + 5y). t is 25 words of scratch.")
w("library KeccakF1600 {")
w("    function permute(uint256 s, uint256 t) internal pure {")
w("        assembly {")
w("            for { let round := 0 } lt(round, 24) { round := add(round, 1) } {")
# theta
w("                {")
for x in range(5):
    w(f"                    let c{x} := xor(xor(xor(xor(mload({off(x)}), mload({off(x + 5)})), mload({off(x + 10)})), mload({off(x + 15)})), mload({off(x + 20)}))")
for x in range(5):
    w(f"                    let d{x} := xor(c{(x - 1) % 5}, {rol(f'c{(x + 1) % 5}', 1)})")
# theta apply + rho + pi into t: B[y][(2x+3y)%5] = rol(A[x][y] ^ D[x], r[x][y])
for y in range(5):
    for x in range(5):
        src = x + 5 * y
        bx, by = y, (2 * x + 3 * y) % 5
        dst = bx + 5 * by
        w(f"                    {{ let a := xor(mload({off(src)}), d{x}) mstore({toff(dst)}, {rol('a', R[x][y])}) }}")
w("                }")
# chi: A[x][y] = B[x][y] ^ (~B[x+1][y] & B[x+2][y])
for y in range(5):
    w("                {")
    for x in range(5):
        w(f"                    let b{x} := mload({toff(x + 5 * y)})")
    for x in range(5):
        w(f"                    mstore({off(x + 5 * y)}, xor(b{x}, and(xor(b{(x + 1) % 5}, {M}), b{(x + 2) % 5})))")
    w("                }")
# iota
w("                let rc := 0")
w("                switch round")
for i, c in enumerate(RC):
    w(f"                case {i} {{ rc := 0x{c:016x} }}")
w("                mstore(s, xor(mload(s), rc))")
w("            }")
w("        }")
w("    }")
w("}")
print("\n".join(out))
