// Copies the compiled contracts (contracts/out, built with `forge build`) into
//   src/artifacts.ts                                     (TypeScript clients)
//   services/wallet-api/internal/qdaccount/artifacts.json (Go relayer)
// Both are committed, so neither the web build nor the API build needs Foundry.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const read = (file, name) => {
  const j = JSON.parse(readFileSync(join(root, 'contracts', 'out', file, `${name}.json`), 'utf8'));
  return { abi: j.abi, bytecode: j.bytecode.object };
};
const artifacts = {
  QdRaccoonVerifier: read('QdRaccoonVerifier.sol', 'QdRaccoonVerifier'),
  QdAccount: read('QdAccount.sol', 'QdAccount'),
  QdAccountFactory: read('QdAccount.sol', 'QdAccountFactory'),
};
const header = '// GENERATED by scripts/gen-artifacts.mjs from contracts/ (solc 0.8.28, see contracts/foundry.toml). Do not edit.\n';
writeFileSync(
  join(root, 'packages', 'qd-account', 'src', 'artifacts.ts'),
  header + Object.entries(artifacts)
    .map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 0)} as const;\n`)
    .join('\n'),
);
writeFileSync(join(root, 'services', 'wallet-api', 'internal', 'qdaccount', 'artifacts.json'), JSON.stringify(artifacts) + '\n');
console.log('artifacts written');
